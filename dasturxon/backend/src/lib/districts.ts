import { haversineKm } from './geo.js';

// Примерные центры районов Ташкента. Повар видит только район покупателя (ТЗ 4.2),
// точный адрес получает курьер через Яндекс Go. Для точных границ районов можно
// заменить на обратное геокодирование Яндекса (kind=district).
const CENTERS: [string, number, number][] = [
  ['Алмазар', 41.350, 69.210], ['Бектемир', 41.210, 69.335], ['Мирабад', 41.290, 69.280],
  ['Мирзо-Улугбек', 41.340, 69.340], ['Сергели', 41.225, 69.220], ['Учтепа', 41.290, 69.170],
  ['Чиланзар', 41.275, 69.200], ['Шайхантахур', 41.320, 69.240], ['Юнусабад', 41.365, 69.290],
  ['Яккасарай', 41.280, 69.255], ['Яшнабад', 41.295, 69.330], ['Янгихаёт', 41.200, 69.195],
];

export function nearestDistrict(lat: number, lon: number): string {
  let best = CENTERS[0][0];
  let bestKm = Infinity;
  for (const [name, la, lo] of CENTERS) {
    const km = haversineKm(lat, lon, la, lo);
    if (km < bestKm) { bestKm = km; best = name; }
  }
  return bestKm > 25 ? 'За пределами Ташкента' : best;
}
